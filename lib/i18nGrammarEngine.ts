interface CompiledPhraseRule {
  regex: RegExp;
  translations: TranslationTuple;
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const COMPILED_DOMAIN_PHRASES: CompiledPhraseRule[] = Object.entries(
  RAW_DOMAIN_PHRASES
)
  .sort((a, b) => b[0].length - a[0].length)
  .map(([enPhrase, translations]) => ({
    regex: new RegExp(`\\b${escapeRegExp(enPhrase)}\\b`, 'gi'),
    translations,
  }));

/**
 * Preserves capitalization style (UPPERCASE, Title Case, lowercase) for Latin scripts.
 */
function applyCasePattern(
  sourceToken: string,
  translated: string,
  lang: NonEnglishLang
): string {
  if (!translated || lang === 'hi') return translated;
  if (sourceToken.length > 1 && sourceToken === sourceToken.toUpperCase()) {
    return translated.toUpperCase();
  }
  const firstChar = sourceToken[0];
  if (
    firstChar &&
    firstChar === firstChar.toUpperCase() &&
    firstChar !== firstChar.toLowerCase()
  ) {
    return translated.charAt(0).toUpperCase() + translated.slice(1);
  }
  return translated;
}

/**
 * Looks up a single English word token in VOCAB_DICTIONARY with morphological
 * stem fallback (possessives, plurals, -ed, -ing, -ly) so inflected forms also translate.
 */
function lookupWordToken(
  token: string,
  tupleIdx: number,
  lang: NonEnglishLang
): string | null {
  const lower = token.toLowerCase();

  // Direct vocabulary hit
  const direct = VOCAB_DICTIONARY[lower];
  if (direct) {
    return applyCasePattern(token, direct[tupleIdx], lang);
  }

  // Possessive 's
  if (lower.endsWith("'s") || lower.endsWith('’s')) {
    const base = lower.slice(0, -2);
    const hit = VOCAB_DICTIONARY[base];
    if (hit) {
      return applyCasePattern(token.slice(0, -2), hit[tupleIdx], lang);
    }
  }

  // Plural -ies -> -y (e.g., categories, frequencies, currencies)
  if (lower.length > 4 && lower.endsWith('ies')) {
    const singular = lower.slice(0, -3) + 'y';
    const hit = VOCAB_DICTIONARY[singular];
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  // Plural -es -> base (e.g., taxes, boxes, inches, matches)
  if (lower.length > 3 && lower.endsWith('es')) {
    const singular = lower.slice(0, -2);
    const hit = VOCAB_DICTIONARY[singular] ?? VOCAB_DICTIONARY[lower.slice(0, -1)];
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  // Plural -s -> base (e.g., calculators, units, payments)
  if (lower.length > 3 && lower.endsWith('s') && !lower.endsWith('ss')) {
    const singular = lower.slice(0, -1);
    const hit = VOCAB_DICTIONARY[singular];
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  // Adverb -ly -> base (e.g., monthly, annually, exactly)
  if (lower.length > 4 && lower.endsWith('ly')) {
    const base = lower.slice(0, -2);
    const hit = VOCAB_DICTIONARY[base] ?? VOCAB_DICTIONARY[base + 'e'];
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  // Progressive -ing -> base or base+e
  if (lower.length > 5 && lower.endsWith('ing')) {
    const stem = lower.slice(0, -3);
    const hit =
      VOCAB_DICTIONARY[stem] ??
      VOCAB_DICTIONARY[stem + 'e'] ??
      (stem.length > 2 && stem[stem.length - 1] === stem[stem.length - 2]
        ? VOCAB_DICTIONARY[stem.slice(0, -1)]
        : undefined);
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  // Past -ed -> base or base+e
  if (lower.length > 4 && lower.endsWith('ed')) {
    const stem = lower.slice(0, -2);
    const hit =
      VOCAB_DICTIONARY[stem] ??
      VOCAB_DICTIONARY[stem + 'e'] ??
      (stem.endsWith('i')
        ? VOCAB_DICTIONARY[stem.slice(0, -1) + 'y']
        : undefined);
    if (hit) {
      return applyCasePattern(token, hit[tupleIdx], lang);
    }
  }

  return null;
}

/**
 * Single-pass protected phrase + vocabulary + morphology translation engine.
 * Protects matched phrases with private-use Unicode placeholders so subsequent
 * phrase or word replacements never corrupt already-translated target text.
 */
export function translateWithGrammarEngine(
  input: string,
  lang: NonEnglishLang,
  extraPhrases?: Array<{
    en: string;
    es: string;
    fr: string;
    de: string;
    hi: string;
  }>
): string {
  const tupleIdx = LANG_TUPLE_INDEX[lang];
  const placeholders: string[] = [];

  const createPlaceholder = (translated: string): string => {
    const idx = placeholders.length;
    placeholders.push(translated);
    return `\uE000${idx}\uE001`;
  };

  let working = input;

  // 1. Apply any caller-provided high-priority multi-word phrases first
  if (extraPhrases && extraPhrases.length > 0) {
    for (const phrase of extraPhrases) {
      if (working.includes(phrase.en)) {
        const ph = createPlaceholder(phrase[lang]);
        working = working.split(phrase.en).join(ph);
      }
    }
  }

  // 2. Apply longest-first domain phrases (case-insensitive with case preservation)
  for (const rule of COMPILED_DOMAIN_PHRASES) {
    working = working.replace(rule.regex, (matched) => {
      const rawTranslated = rule.translations[tupleIdx];
      const cased = applyCasePattern(matched, rawTranslated, lang);
      return createPlaceholder(cased);
    });
  }

  // 3. Single-pass word tokenizer on remaining English words
  working = working.replace(
    /\b[A-Za-z]+(?:'[A-Za-z]+|’[A-Za-z]+)?\b/g,
    (wordToken) => {
      // Do not translate brand name
      if (
        wordToken === 'SolveItCalculator' ||
        wordToken === 'SolveIt'
      ) {
        return wordToken;
      }
      const translatedWord = lookupWordToken(wordToken, tupleIdx, lang);
      if (translatedWord === null) {
        return wordToken;
      }
      return translatedWord;
    }
  );

  // 4. Restore protected phrase placeholders
  working = working.replace(/\uE000(\d+)\uE001/g, (_, idxStr) => {
    const idx = Number(idxStr);
    return placeholders[idx] ?? '';
  });

  // Clean up any double spaces produced when Hindi omits articles ("the")
  return working.replace(/ {2,}/g, ' ').trim();
}
